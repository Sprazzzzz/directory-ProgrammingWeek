def Sum_of_1_to_n(n): #สร้างฟังก์ชันเพื่อใช้คำนวณ

    sum = 0 #สร้างตัวแปร sum เพื่อเก็บผลรวม
    for i in range(1, n + 1): #ใช้ลูป for เพื่อวนซ้ำตั้งแต่ 1 ถึง n
        sum += i #เพิ่มค่าของ i เข้าไปใน sum
    print("Sum of 1 to", n, "is:", sum) #แสดงผลลัพธ์ของผลรวม

Sum_of_1_to_n(10) #เรียกใช้ฟังก์ชันเพื่อคำนวณผลรวมของ 1 ถึง 10